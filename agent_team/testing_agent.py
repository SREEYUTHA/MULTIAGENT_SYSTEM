def _parse_json(response: str) -> dict:
    """Parse JSON and validate the Testing Agent's response."""

    response = response.strip()

    if response.startswith("```"):
        lines = response.splitlines()
        lines = lines[1:]

        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]

        response = "\n".join(lines).strip()

    start = response.find("{")
    end = response.rfind("}")

    if start == -1 or end == -1 or end < start:
        print("\nNo complete JSON object found.")
        print("Response ending:", repr(response[-500:]))
        raise ValueError("Testing Agent returned no complete JSON object.")

    candidate = response[start:end + 1]

    try:
        result = json.loads(candidate)

    except json.JSONDecodeError as exc:
        print("\nTESTING AGENT JSON PARSING FAILED")
        print("Error:", exc)
        print("Line:", exc.lineno)
        print("Column:", exc.colno)
        print("Position:", exc.pos)
        print("Response length:", len(response))
        print("Response ending:", repr(response[-500:]))

        raise ValueError("Testing Agent returned malformed JSON.") from exc

    try:
        validated_proposal = TestingProposal.model_validate(result)
    except ValidationError as exc:
        print("\nTESTING AGENT SCHEMA VALIDATION FAILED")
        print(exc)

        print("\nReceived JSON fields:")
        print(list(result.keys()))

        missing_fields = [
            error["loc"][0]
            for error in exc.errors()
            if error["type"] == "missing"
        ]

        print("\nMissing fields:", missing_fields)

        raise ValueError(
            f"Testing Agent schema validation failed. "
            f"Missing fields: {missing_fields}. "
            f"Full error: {exc}"
        ) from exc

    result = validated_proposal.model_dump()
    result["agent"] = "Testing Engineer"

    return result


def _ask_testing_agent(user_prompt: str) -> dict:
    """Request JSON and retry once if the response is invalid."""

    response = ask_llm(TESTING_SYSTEM_PROMPT, user_prompt)

    try:
        return _parse_json(response)

    except ValueError as first_error:
        print("\nRetrying Testing Agent once because its response was invalid...")

        repair_prompt = f"""
Your previous response failed JSON or schema validation.

ERROR DETAILS:
{first_error}

You MUST return a NEW, COMPLETE JSON object.

The following fields are mandatory:

1. agent
2. summary
3. requirements_review
4. frontend_backend_conflicts
5. test_scenarios
6. validation_checks
7. security_checks
8. risks
9. feedback_review
10. open_questions
11. blockers

IMPORTANT:
- Never omit any field.
- Use [] when a list has no findings.
- All arrays except test_scenarios must contain strings.
- test_scenarios must contain valid scenario objects.
- Maximum 5 requirements_review items.
- Maximum 3 items in every other list.
- Follow the exact TestingProposal schema.
- Return valid JSON only.
- Do not use Markdown fences.
- Do not claim tests were executed.

Original task:
{user_prompt}

Previous invalid response:
{response[-3000:]}
"""

        retry_response = ask_llm(
            TESTING_SYSTEM_PROMPT,
            repair_prompt,
        )

        try:
            return _parse_json(retry_response)
        except ValueError as retry_error:
            raise ValueError(
                "Testing Agent failed to return valid JSON after one retry. "
                "Check the LLM finish reason and response diagnostics."
            ) from retry_error



def propose_testing(
    project_idea: str,
    frontend_proposal: dict,
    backend_proposal: dict,
    api_contract: dict,
    technology_plan: dict,
) -> dict:
    """Create a test strategy using proposals and the shared contract."""

    user_prompt = f"""
APPLICATION IDEA:
{project_idea}
TECHNOLOGY STACK PLAN:

{json.dumps(technology_plan, separators=(",", ":"))}

SHARED API CONTRACT:
{json.dumps(api_contract, separators=(",", ":"))}

FRONTEND PROPOSAL:
{json.dumps(frontend_proposal, separators=(",", ":"))}

BACKEND PROPOSAL:
{json.dumps(backend_proposal, separators=(",", ":"))}

Review both proposals against the application idea and mandatory API contract.

Identify missing endpoints, API mismatches, validation issues,
security risks, and up to three essential test scenarios.

Report genuine blockers and unresolved conflicts.
Do not claim tests were executed.
TECHNOLOGY VALIDATION:

- Verify that the frontend follows the approved technology stack.
- Verify that the backend follows the approved technology stack.
- Identify any differences from explicitly requested technologies.
- Check whether recommended technologies are used appropriately.
- Report genuine technology conflicts.
- Do not report a technology as missing if it is not required.

Return a concise, complete JSON report.
"""


    return _ask_testing_agent(user_prompt)




def review_testing(
    project_idea: str,
    own_proposal: dict,
    peer_feedback: dict,
    api_contract: dict,
    technology_plan: dict,
) -> dict:
    """Revise the testing plan using feedback and the shared API contract."""

    user_prompt = f"""
APPLICATION IDEA:
{project_idea}
TECHNOLOGY STACK PLAN:

{json.dumps(technology_plan, separators=(",", ":"))}

SHARED API CONTRACT:
{json.dumps(api_contract, separators=(",", ":"))}

CURRENT TESTING PROPOSAL:
{json.dumps(own_proposal, separators=(",", ":"))}

PEER FEEDBACK:
{json.dumps(peer_feedback, separators=(",", ":"))}

Review the revised frontend and backend proposals.

Verify mandatory API coverage, correct genuine QA findings,
update essential test scenarios, and retain unresolved blockers.

Preserve valid findings. Do not invent conflicts or claim tests were executed.
During final QA, verify that the revised frontend and backend
still follow the approved Technology Stack Plan.
Do not silently approve changes to explicitly requested technologies.

Return the complete, concise JSON report.
"""


    return _ask_testing_agent(user_prompt)

